import { randomUUID } from 'node:crypto'
import { PrismaService } from '../prisma/prisma.service'
import { tenantContext } from '../prisma/tenant.context'
import { ClubEntitlementsService } from '../billing/club-entitlements.service'
import { StudioService } from './studio.service'
import { StudioController } from './studio.controller'

// Never use DATABASE_URL implicitly: this suite only touches a disposable local DB.
const databaseUrl = process.env.ANSTOSS_STUDIO_TEST_DATABASE_URL
if (databaseUrl) {
  const url = new URL(databaseUrl)
  if (url.hostname !== '127.0.0.1' || !url.pathname.endsWith('_test')) {
    throw new Error('Studio tests require an isolated localhost *_test database')
  }
}
const databaseTests = databaseUrl ? describe : describe.skip

databaseTests(
  'Studio PostgreSQL: real permissions, plan, context and brand-kit persistence',
  () => {
    const run = `studio-test-${randomUUID()}`
    let db: PrismaService
    let controller: StudioController
    let clubId: string
    let otherClubId: string
    let teamId: string
    let otherTeamId: string
    let adminId: string
    let captainId: string
    let outsiderId: string
    let eventId: string
    let otherEventId: string
    let sponsorId: string
    let foreignSponsorId: string
    // Prisma promises are lazy: await inside the context so middleware sees it.
    const asClub = <T>(fn: () => Promise<T>) =>
      tenantContext.run({ clubId, userId: adminId }, async () => await fn())

    beforeAll(async () => {
      db = new PrismaService({ datasources: { db: { url: databaseUrl! } } })
      // Register actual tenant middleware, unlike a bare PrismaClient unit test.
      await db.onModuleInit()
      const plans = new ClubEntitlementsService(db, {} as never)
      controller = new StudioController(new StudioService(db, plans))
      adminId = (await db.user.create({ data: { name: `${run}-admin` } })).id
      captainId = (await db.user.create({ data: { name: `${run}-captain` } })).id
      outsiderId = (await db.user.create({ data: { name: `${run}-outsider` } })).id
      clubId = (await db.club.create({ data: { name: run, slug: run, primaryColor: '#123456' } }))
        .id
      otherClubId = (await db.club.create({ data: { name: `${run}-other`, slug: `${run}-other` } }))
        .id
      await db.membership.createMany({
        data: [
          { clubId, userId: adminId, role: 'ADMIN' },
          { clubId, userId: captainId, role: 'PLAYER', operationalRoles: ['CAPTAIN'] },
        ],
      })
      await db.entitlementGrant.create({ data: { clubId, tier: 'PRO', source: 'COMPLIMENTARY' } })
      sponsorId = (
        await db.sponsor.create({
          data: { clubId, name: 'Local sponsor', logoUrl: 'https://example.test/local.png' },
        })
      ).id
      foreignSponsorId = (
        await db.sponsor.create({
          data: {
            clubId: otherClubId,
            name: 'Other sponsor',
            logoUrl: 'https://example.test/other.png',
          },
        })
      ).id
      await asClub(async () => {
        const group = await db.teamGroup.create({
          data: { clubId, type: 'SENIOR', displayName: 'Seniors' },
        })
        teamId = (
          await db.team.create({
            data: { clubId, groupId: group.id, name: 'One', displayName: 'One' },
          })
        ).id
        otherTeamId = (
          await db.team.create({
            data: { clubId, groupId: group.id, name: 'Two', displayName: 'Two' },
          })
        ).id
        await db.teamAccess.create({
          data: {
            clubId,
            teamId,
            userId: captainId,
            role: 'PLAYER',
            phase: 'FULL',
            status: 'ACTIVE',
          },
        })
        eventId = (
          await db.event.create({
            data: {
              clubId,
              teamId,
              title: 'Match one',
              type: 'MATCH',
              date: new Date(Date.now() + 3600000),
              createdById: adminId,
            },
          })
        ).id
        otherEventId = (
          await db.event.create({
            data: {
              clubId,
              teamId: otherTeamId,
              title: 'Match two',
              type: 'MATCH',
              date: new Date(Date.now() + 1800000),
              createdById: adminId,
            },
          })
        ).id
      })
    }, 30000)

    afterAll(async () => {
      // Exact IDs generated by this run; cascades remove only its fixtures.
      if (clubId) await db.club.delete({ where: { id: clubId } })
      if (otherClubId) await db.club.delete({ where: { id: otherClubId } })
      await db.user.deleteMany({
        where: { id: { in: [adminId, captainId, outsiderId].filter(Boolean) } },
      })
      await db.$disconnect()
    })

    it('persists brand settings through controller/service/database and a fresh service instance', async () => {
      const saved = await controller.updateBrandKit(
        clubId,
        { id: adminId },
        {
          fontPairing: 'MODERN',
          handle: '@testclub',
          hashtags: ['#testclub'],
          sponsors: [{ id: sponsorId, name: 'Our sponsor' }],
        },
      )
      expect(saved.fontPairing).toBe('MODERN')
      const fresh = new StudioService(db, new ClubEntitlementsService(db, {} as never))
      const reread = await fresh.brandKit(clubId, adminId)
      expect(reread.handle).toBe('@testclub')
      expect(reread.sponsors).toEqual([
        { id: sponsorId, name: 'Our sponsor', logoUrl: 'https://example.test/local.png' },
      ])
      expect(reread.accounts.every((account) => !account.connected)).toBe(true)
    })

    it('preserves independent concurrent partial edits', async () => {
      await Promise.all([
        controller.updateBrandKit(clubId, { id: adminId }, { fontPairing: 'CLASSIC' }),
        controller.updateBrandKit(clubId, { id: adminId }, { handle: '@updated' }),
      ])
      expect(await controller.brandKit(clubId, { id: adminId })).toMatchObject({
        fontPairing: 'CLASSIC',
        handle: '@updated',
      })
    })

    it('limits captain context to the active team, even when another team plays sooner', async () => {
      expect(await controller.context(clubId, { id: captainId }, {})).toEqual({
        eventId,
        consents: [],
      })
      await expect(
        controller.context(clubId, { id: captainId }, { eventId: otherEventId }),
      ).rejects.toThrow()
      await expect(
        controller.context(clubId, { id: captainId }, { teamId: otherTeamId }),
      ).rejects.toThrow()
      await expect(
        controller.updateBrandKit(clubId, { id: captainId }, { handle: '@takeover' }),
      ).rejects.toThrow()
    })

    it('rejects outsiders, foreign route clubs and foreign sponsors', async () => {
      await expect(controller.brandKit(clubId, { id: outsiderId })).rejects.toThrow()
      await expect(controller.context(otherClubId, { id: adminId }, { eventId })).rejects.toThrow()
      await expect(
        controller.updateBrandKit(
          clubId,
          { id: adminId },
          { sponsors: [{ id: foreignSponsorId, name: 'Foreign' }] },
        ),
      ).rejects.toThrow()
      expect((await controller.brandKit(clubId, { id: adminId })).sponsors[0].id).toBe(sponsorId)
    })

    it('does not provide context for revoked, expired or not-yet-started access', async () => {
      for (const patch of [
        { status: 'REVOKED' as const },
        { status: 'ACTIVE' as const, loanEndDate: new Date(Date.now() - 1000) },
        {
          status: 'ACTIVE' as const,
          loanEndDate: null,
          loanStartDate: new Date(Date.now() + 3600000),
        },
      ]) {
        await asClub(() =>
          db.teamAccess.updateMany({ where: { clubId, userId: captainId }, data: patch }),
        )
        await expect(controller.context(clubId, { id: captainId }, {})).rejects.toThrow()
      }
      await asClub(() =>
        db.teamAccess.updateMany({
          where: { clubId, userId: captainId },
          data: { status: 'ACTIVE', loanEndDate: null, loanStartDate: null },
        }),
      )
    })

    it('requires an active paid entitlement rather than trusting the client', async () => {
      await db.entitlementGrant.updateMany({
        where: { clubId },
        data: { expiresAt: new Date(Date.now() - 1000) },
      })
      await expect(controller.brandKit(clubId, { id: adminId })).rejects.toThrow('Verein plan')
      await db.entitlementGrant.updateMany({ where: { clubId }, data: { expiresAt: null } })
    })

    it('fails closed on unscoped reads and does not resurrect deleted sponsor assets', async () => {
      await expect(db.studioBrandKit.findUnique({ where: { clubId } })).rejects.toThrow(
        'club context',
      )
      await db.sponsor.delete({ where: { id: sponsorId } })
      expect((await controller.brandKit(clubId, { id: adminId })).sponsors).toEqual([])
    })
  },
)
